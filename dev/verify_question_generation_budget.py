"""Question-only native duration trials with a real default-recipe regression."""
import json
import os
from pathlib import Path
import sys
import uuid

ROOT=Path(__file__).resolve().parents[1]
sys.path[:0]=[str(ROOT),str(ROOT/'core')]
os.environ['PATH']=str(ROOT/'ffmpeg/bin')+os.pathsep+os.environ.get('PATH','')
os.environ.update(HF_HUB_OFFLINE='1',TRANSFORMERS_OFFLINE='1',REFLOW_OFFLINE='1')


def main():
    import numpy as np
    import soundfile as sf
    from pydub import AudioSegment
    from core.cue_review import digest
    from core.providers.tts.indicf5_local import IndicF5TTSProvider
    from core.render_context import RenderContext,bind_job,run_process
    base=ROOT/'docs/validation'
    original=json.loads((base/'2026-10-08-spoken-hindi-full-video-887151ac.json').read_text(encoding='utf-8'))
    accepted=json.loads((base/'2026-10-08-shot-bounded-hindi-38a36120.json').read_text(encoding='utf-8'))
    cue=original['cues'][11]
    original_pcm,rate=sf.read(Path(original['directory'])/cue['file'],dtype='int16')
    first=cue['result']['sentences'][0]
    text=first['text']
    assert text=='ऊब गए?'
    expected_pcm=original_pcm[:first['frames']]
    profile=ROOT/'models/indicf5/references/abhishek/profile.json'
    profile_hash=digest(profile)
    protected={row['shot']:digest(row['output']) for row in accepted['phrases']}
    folder=base/('2026-10-09-question-generation-budget-'+uuid.uuid4().hex[:8])
    folder.mkdir()
    report=dict(completed=False,human_accepted=False,text=text,production_defaults_changed=False,
        voice_profile_changed=False,post_synthesis_time_stretch=False,integrated_into_video=False,
        trials=[],profile_sha256=profile_hash,default_pcm_regression_pass=False)
    job=RenderContext(ROOT/'temp')
    provider=None
    try:
        with bind_job(job):
            provider=IndicF5TTSProvider(str(ROOT/'models/indicf5/evaluation/assets'),str(profile),'cuda:0')
            for name,floor in [('A',.9),('B',1.1),('default-regression',None)]:
                output=folder/(name+'.wav')
                predicted=provider.estimate_duration_seconds(text,minimum_sentence_seconds=floor)
                print('Generating '+name+' at '+str(round(predicted,3))+' seconds',flush=True)
                provider.synthesize(text,str(output),'hi',provider.profile['reference_audio'],minimum_sentence_seconds=floor)
                actual,actual_rate=sf.read(output,dtype='int16')
                assert actual_rate==rate==24000 and abs(len(actual)/rate-predicted)<1/rate
                if floor is not None:
                    assert len(actual)/rate>=floor
                else:
                    assert np.array_equal(actual,expected_pcm),'Default question PCM changed after explicit-floor requests.'
                    report['default_pcm_regression_pass']=True
                report['trials'].append(dict(name=name,minimum_sentence_seconds=floor,predicted_seconds=predicted,
                    actual_seconds=len(actual)/rate,file=str(output),sha256=digest(output),result=provider.last_result))
            assert len({row['result']['worker_pid'] for row in report['trials']})==1
            provider.release()
            provider=None
            pair=AudioSegment.silent(duration=250,frame_rate=24000)+AudioSegment.from_file(folder/'A.wav')
            pair+=AudioSegment.silent(duration=900,frame_rate=24000)+AudioSegment.from_file(folder/'B.wav')
            pair+=AudioSegment.silent(duration=400,frame_rate=24000)
            listening=folder/'QUESTION_A_THEN_B.wav'
            pair.export(listening,format='wav').close()
            run_process(['ffmpeg','-v','error','-nostdin','-i',str(listening),'-f','null','-'],capture_output=True,check=True)
            assert digest(profile)==profile_hash
            assert digest(accepted['output'])==accepted['output_sha256']
            assert all(digest(row['output'])==protected[row['shot']] for row in accepted['phrases'])
            report.update(completed=True,one_worker_reused=True,worker_released=not getattr(job,'_indicf5_sessions',{}),
                full_decode_pass=True,listening=str(listening),listening_sha256=digest(listening),
                accepted_clip_and_three_phrases_unchanged=True,
                note='Explicit generation-duration floor for question trials only. Default call regenerated byte-identical accepted original-question PCM. Neither candidate fits the existing 0.6-second intro slot.')
    except Exception as exc:
        report.update(error=str(exc),error_type=type(exc).__name__)
        raise
    finally:
        if provider is not None:
            provider.release()
        job.cleanup()
        report['workspace_removed']=not job.workspace.exists()
        folder.with_suffix('.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
        print(folder.with_suffix('.json'),flush=True)


if __name__=='__main__':
    main()
